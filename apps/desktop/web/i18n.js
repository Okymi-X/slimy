export const detectLanguage = () => ((typeof navigator !== 'undefined' && navigator.language) || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';

export function say(language, key, vars = {}) {
  const table = STRINGS[language] ?? STRINGS.en;
  const template = table[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

/** Turns a backend error (a short code, or "provider:message") into a sentence in the slime's voice. */
export function explain(language, error) {
  const text = String(error);
  if (text.startsWith('provider:')) return say(language, 'providerSays', { message: text.slice(9) });
  if (text.startsWith('mcp_server:')) return say(language, 'mcpServerSays', { message: text.slice(11) });
  return say(language, text);
}
